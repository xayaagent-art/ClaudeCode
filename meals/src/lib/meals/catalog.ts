function buildIngredients(recipeId: string, list: IngredientSpec[]): RecipeIngredient[] {
  return list.map((ing, index) => ({
    id: `${recipeId}-ing-${index}`,
    recipe_id: recipeId,
    ingredient_name: ing.name,
    quantity: ing.quantity ?? null,
    unit: ing.unit ?? null,
    optional: ing.optional ?? false,
  }));
}

export const catalogRecipes: Recipe[] = specs.map((spec) => ({
  id: spec.id,
  title: spec.title,
  description: spec.description,
  cuisine: spec.cuisine,
  image_url: null,
  prep_time_minutes: spec.prep,
  cook_time_minutes: spec.cook,
  total_time_minutes: spec.prep + spec.cook,
  servings: spec.servings,
  calories_per_serving: spec.calories,
  protein_per_serving: spec.protein,
  dietary_tags: spec.tags,
  source_type: "catalog",
  source_url: null,
  instructions: spec.instructions,
  ingredients: buildIngredients(spec.id, spec.ingredients),
  created_at: "2026-08-01T00:00:00.000Z",
}));

export function findCatalogRecipe(id: string): Recipe | undefined {
  return catalogRecipes.find((r) => r.id === id);
}
